--  ЗАДАЧА
--    Всё, что может часто меняться (контакты, цены доставки, слоганы,
--    логотип, промо-картинка), хранится в базе, а не зашито в HTML.
--    Сайт подтягивает значения при загрузке.
--
--  КАК ЭТО РАБОТАЕТ
--    В HTML у элемента стоит атрибут data-content="ключ":
--        <span data-content="brand.tagline">эпоксидная смола и фетр</span>
--    При загрузке страницы сайт читает таблицу и подставляет значение по ключу.
--    Текст внутри тега — запасной вариант: если база недоступна или ключа нет,
--    посетитель всё равно увидит нормальный сайт.
--
--    Для картинок используется data-content-src="ключ" (логотип, промо-фото),
--    для ссылок — data-content-href="ключ".
--
--  БЕЗОПАСНОСТЬ
--    Чтение — всем. Изменение — только через панель Supabase (Table Editor),
--    анонимная запись закрыта.
--
--  Скрипт идемпотентен: повторный запуск не дублирует строки и не затирает
--  ваши правки (существующие значения НЕ перезаписываются).
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. Таблица
-- ----------------------------------------------------------------------------
create table if not exists public.site_content (
    id          serial primary key,
    key         text not null unique,
    value       text,
    description text,                          -- подсказка: где это видно на сайте
    updated_at  timestamptz default now()
);

comment on table  public.site_content             is 'Тексты и картинки сайта, которые могут часто меняться';
comment on column public.site_content.key         is 'Ключ, совпадает с атрибутом data-content в HTML';
comment on column public.site_content.value       is 'Значение. Пустое значение для картинок означает «показать заглушку»';
comment on column public.site_content.description is 'Пояснение для того, кто правит контент в Table Editor';


-- ----------------------------------------------------------------------------
-- 2. Дата изменения обновляется автоматически
-- ----------------------------------------------------------------------------
create or replace function public.site_content_touch_updated_at()
returns trigger language plpgsql as $$
begin
    new.updated_at := now();
    return new;
end;
$$;

drop trigger if exists site_content_updated_at on public.site_content;
create trigger site_content_updated_at
    before update on public.site_content
    for each row execute function public.site_content_touch_updated_at();


-- ----------------------------------------------------------------------------
-- 3. Защита (RLS): читать всем, менять только из панели администратора
-- ----------------------------------------------------------------------------
alter table public.site_content enable row level security;
grant select on public.site_content to anon, authenticated;

drop policy if exists "public_read_site_content" on public.site_content;
create policy "public_read_site_content" on public.site_content
    for select to anon, authenticated
    using (true);


